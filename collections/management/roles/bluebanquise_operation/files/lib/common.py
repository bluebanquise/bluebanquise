"""
Shared code of bluebanquise-operation: used by its two daemons (api, worker). Installed in
/usr/lib/bluebanquise/bluebanquise-operation/lib/, and imported with a plain `import common`
after adding this folder to sys.path.

Power and boot actions are run by bluebanquise-power (bluebanquise_power role), never by this
pack: the worker runs its command line with --json, and reads the result it prints on stdout.
BMC credentials are read by bluebanquise-power only.

Files, under data_path (/var/lib/bluebanquise-operation):
  power.yml               power state of every host, written by the worker only
  power-status.json       result of the last power status command (its stdout)
  power-status.log        logs of the last power status command (its stderr)
  jobs/<job id>.yml       a power or boot action (the job), see request_job()
  jobs/<job id>.json      result of its bluebanquise-power command (its stdout)
  jobs/<job id>.log       logs of its bluebanquise-power command (its stderr)
  requests/<job id>       empty file: the job waits for the worker
Console logs are written by conmand (conman role), one file per host, read only.

Every file is written atomically (temporary file in the same folder, then os.replace()), so a
reader never sees a half-written file.
"""

import grp
import json
import logging
import os
import pwd
import re
import sys
import threading
import time
import uuid

import yaml
from ClusterShell.NodeSet import NodeSet

SETTINGS_FILE = '/etc/bluebanquise/bluebanquise-operation/bluebanquise-operation.yml'

LOG_FORMAT = '%(asctime)s [%(levelname)s] %(message)s'

# Actions and their parameters, as bluebanquise-power names them. "power status" is not an
# action: the worker reads the power state of every host by itself.
ACTIONS = {
    'power': ['on', 'off', 'reset'],
    'boot': ['pxe', 'disk', 'bios'],
}


# ─── settings, logging, privileges ─────────────────────────────────────────────

# Control characters, written as \xNN in logs (new line and carriage return as \n and \r)
CONTROL_CHARACTERS = re.compile(r'[\x00-\x1f\x7f-\x9f]')

# A log line longer than this is cut: journald splits longer lines (48K bytes by default)
MAX_LOG_LINE = 8000


def escape_control_character(match):
    return '\\x{:02x}'.format(ord(match.group()))


class OneLineFormatter(logging.Formatter):
    """One journal line per log call: text coming from a user or a BMC can never start a line of
    its own, so it can never forge a line (an AUDIT line for example). Same as
    common.OneLineFormatter of bluebanquise-supervision."""

    def format(self, record):
        line = super().format(record)
        line = line.replace('\n', '\\n').replace('\r', '\\r')
        line = CONTROL_CHARACTERS.sub(escape_control_character, line)
        if len(line) > MAX_LOG_LINE:
            line = line[:MAX_LOG_LINE] + '... (cut)'
        return line


def setup_logging(log_level):
    level = getattr(logging, str(log_level).upper(), logging.INFO)
    root = logging.getLogger()
    root.setLevel(level)
    if not root.handlers:
        handler = logging.StreamHandler(sys.stdout)
        handler.setFormatter(OneLineFormatter(LOG_FORMAT))
        root.addHandler(handler)


def load_settings(path=SETTINGS_FILE):
    with open(path, 'r') as f:
        return yaml.safe_load(f)


def load_hosts(settings):
    """Hosts with a BMC, as generated by the role from the inventory."""
    with open(settings['hosts_file'], 'r') as f:
        data = yaml.safe_load(f) or {}
    return data.get('hosts') or {}


def drop_privileges(user):
    """If started as root, switch to the pack user (conman) before touching any file, so every
    file keeps the right owner."""
    os.umask(0o027)
    if os.getuid() != 0:
        return
    pw = pwd.getpwnam(user)
    # Groups of the user, as systemd gives them to the services: bluebanquise-webui (WebUI users
    # file) and bluebanquise (bluebanquise-power configuration)
    os.initgroups(user, pw.pw_gid)
    os.setgid(pw.pw_gid)
    os.setuid(pw.pw_uid)
    os.environ['HOME'] = pw.pw_dir
    logging.debug('Dropped privileges to %s (uid=%d gid=%d, group %s)',
                  user, pw.pw_uid, pw.pw_gid, grp.getgrgid(pw.pw_gid).gr_name)


# ─── files ──────────────────────────────────────────────────────────────────────

def read_yaml(path, default):
    try:
        with open(path, 'r') as f:
            data = yaml.safe_load(f)
    except FileNotFoundError:
        return default
    if data is None:
        return default
    return data


def write_yaml(path, data):
    """Atomic write: temporary file in the same folder, then os.replace(). The temporary file
    name holds the process and thread ids, so two writers never share it."""
    folder = os.path.dirname(path)
    tmp_path = os.path.join(folder, '.{}.{}.{}.tmp'.format(
        os.path.basename(path), os.getpid(), threading.get_ident()))
    with open(tmp_path, 'w') as f:
        yaml.safe_dump(data, f, default_flow_style=False, allow_unicode=True, sort_keys=False)
    os.replace(tmp_path, path)


# ─── jobs ───────────────────────────────────────────────────────────────────────
#   1. request_job() (API) writes the job file, jobs/<job id>.yml, state running, then the
#      request file, requests/<job id>.
#   2. The worker sees the request file, removes it, and runs bluebanquise-power --json, its
#      result going to jobs/<job id>.json and its logs to jobs/<job id>.log.
#   3. When bluebanquise-power ends, the worker ends the job: success (every host OK) or failed,
#      with the result of every host.
# Times are seconds since 1970. Job files older than JOBS_KEPT_DAYS are removed by the worker.

JOBS_KEPT_DAYS = 7


def job_file(settings, job_id):
    return os.path.join(settings['jobs_path'], job_id + '.yml')


def job_log_file(settings, job_id):
    return os.path.join(settings['jobs_path'], job_id + '.log')


def job_result_file(settings, job_id):
    return os.path.join(settings['jobs_path'], job_id + '.json')


def valid_job_id(job_id):
    """True for a job id made by request_job() (a uuid): checked before building a path."""
    try:
        return str(uuid.UUID(job_id)) == job_id
    except ValueError:
        return False


def read_job(settings, job_id):
    return read_yaml(job_file(settings, job_id), None)


def write_job(settings, job):
    write_yaml(job_file(settings, job['job']), job)


def list_jobs(settings):
    """Every job, the newest first."""
    jobs = []
    for filename in os.listdir(settings['jobs_path']):
        job_id = filename[:-len('.yml')]
        if not filename.endswith('.yml') or not valid_job_id(job_id):
            continue
        job = read_job(settings, job_id)
        if job is not None:
            jobs.append(job)
    jobs.sort(key=lambda job: job['started'], reverse=True)
    return jobs


def request_job(settings, action, parameter, hosts, by):
    """Ask the worker to run "bluebanquise-power <hosts> <action> <parameter>". hosts is a
    nodeset (c[001-004]) of known hosts, checked by the caller. Returns the job."""
    job = {
        'job': str(uuid.uuid4()),
        'action': action,
        'parameter': parameter,
        'hosts': hosts,
        'by': by,
        'state': 'running',
        'message': 'Waiting for the worker',
        'started': int(time.time()),
        'ended': None,
        'command': None,
        'results': {},
    }
    write_job(settings, job)
    # Written under a temporary name (starting with a dot, ignored by the worker), then renamed:
    # the worker never sees a request before its job file
    tmp_path = os.path.join(settings['requests_path'], '.' + job['job'] + '.tmp')
    with open(tmp_path, 'w') as f:
        f.write('')
    os.replace(tmp_path, os.path.join(settings['requests_path'], job['job']))
    return job


def update_job(settings, job_id, state, message, results=None):
    """Change the state and message of a job. A state other than running ends the job."""
    job = read_job(settings, job_id)
    if job is None:
        logging.warning('Job %s: no job file, can not set it to %s', job_id, state)
        return
    job['state'] = state
    job['message'] = message
    if results is not None:
        job['results'] = results
    if state != 'running':
        job['ended'] = int(time.time())
    write_job(settings, job)
    logging.info('Job %s (%s %s %s by %s) %s: %s', job_id, job['action'], job['parameter'],
                 job['hosts'], job['by'], state, message)


def job_hosts(job):
    """Hosts of a job, as a list."""
    return list(NodeSet(job['hosts']))


# ─── result of bluebanquise-power ─────────────────────────────────────────────

def read_power_result(path):
    """Read the result printed by bluebanquise-power --json on its stdout (saved to path):

        {"nodes": {"c001": {"ok": true, "detail": "on"},
                   "c002": {"ok": false, "detail": "could not get node power status"}}}

    Returns {host: {'ok': True/False, 'detail': '...'}}, or None when there is no result
    (bluebanquise-power stopped before the end: its logs say why)."""
    try:
        with open(path, 'r') as f:
            result = json.load(f)
    except (OSError, ValueError):
        return None
    if not isinstance(result, dict) or not isinstance(result.get('nodes'), dict):
        return None
    return result['nodes']


# ─── power state ────────────────────────────────────────────────────────────────

def read_power(settings):
    """Power state of every host: {host: {'ok': ..., 'detail': ..., 'as_of': ...}}. detail is
    the power state when ok (on, off), else what went wrong with the BMC."""
    return read_yaml(settings['power_file'], {})


def host_power(power_entry):
    """State of a host for the pages and the federator contract: (state, text, power).
         ok       the BMC answered: power is on or off (a host powered off is not an error:
                  Supervision tells whether it should be on)
         error    the BMC did not answer: the host can not be powered on or off from here
         unknown  power state not read yet, or a state other than on and off
    power is "on", "off", another state given by the BMC, or None."""
    if power_entry is None:
        return 'unknown', 'power state not read yet', None
    if not power_entry['ok']:
        return 'error', 'BMC error: ' + power_entry['detail'], None
    power = power_entry['detail'].lower()
    if power == 'on' or power == 'off':
        return 'ok', power, power
    return 'unknown', power, power


# ─── consoles ───────────────────────────────────────────────────────────────────
# Console logs grow all the time: a page polls them, giving back the offset and the inode of the
# last answer. Log rotation (rename, then conmand reopens the file on SIGHUP) gives a new inode.

CONSOLE_FIRST_READ = 64 * 1024
CONSOLE_MAX_READ = 256 * 1024
ANSI = re.compile(r'\x1b\[[0-?]*[ -/]*[@-~]|\x1b\][^\x07]*(\x07|\x1b\\)|\x1b[@-Z\\-_]')
CONSOLE_CONTROL = re.compile(r'[\x00-\x08\x0b-\x1f\x7f]')


def console_file(settings, hostname):
    return os.path.join(settings['console_path'], hostname + '.log')


def read_console(settings, hostname, offset, inode):
    """Next part of the console log of a host. offset and inode come from the previous answer,
    both None for the first call. Returns {offset, inode, reset, text}:
      - first call: the last CONSOLE_FIRST_READ bytes only, reset is true;
      - the file changed (other inode, or smaller than offset: rotated): read the new file from
        its start, reset is true. Lines written between the last call and the rotation are lost;
      - else: what was written since offset.
    At most CONSOLE_MAX_READ bytes per answer. Escape sequences (colors, cursor moves of BIOS
    screens) and control characters are removed, \\r\\n becomes \\n.
    Raises FileNotFoundError when the host has no console log."""
    with open(console_file(settings, hostname), 'rb') as f:
        size = os.fstat(f.fileno()).st_size
        file_inode = os.fstat(f.fileno()).st_ino
        reset = False
        if offset is None:
            start = max(0, size - CONSOLE_FIRST_READ)
            reset = True
        elif inode != file_inode or size < offset:
            start = 0
            reset = True
        else:
            start = offset
        f.seek(start)
        data = f.read(CONSOLE_MAX_READ)

    text = data.decode('utf-8', errors='replace')
    text = ANSI.sub('', text).replace('\r\n', '\n')
    text = CONSOLE_CONTROL.sub('', text)
    return {'offset': start + len(data), 'inode': file_inode, 'reset': reset, 'text': text}
