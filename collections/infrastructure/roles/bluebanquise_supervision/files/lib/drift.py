"""
Drift check of bluebanquise-supervision: compare what is really on a host (output of the
ssh_gather script) with what the inventory expects (the "expected" block of the host in
hosts.yml, generated by the role).

Only values present in "expected" are compared: a value not set in the inventory is never a
drift. Each comparison is written explicitly, field by field, so it is easy to read and change.

parse_gathered(text) -> dict of gathered values (written to gathered.yml)
compare(expected, gathered) -> list of findings (strings), empty when no drift
"""

import json
import shlex

# /etc/os-release ID values that differ from the os_operating_system.distribution names used
# in the inventory. Any other ID is compared as is.
OS_RELEASE_IDS = {
    'rhel': 'redhat',
    'opensuse-leap': 'opensuse',
}


# ─── gathered data parsing ─────────────────────────────────────────────────────

def split_sections(text):
    """'### name' lines start a new section. Returns {name: [lines]}."""
    sections = {}
    current = None
    for line in text.splitlines():
        if line.startswith('### '):
            current = line[4:].strip()
            sections[current] = []
        elif current is not None:
            sections[current].append(line)
    return sections


def parse_gathered(text):
    sections = split_sections(text)
    gathered = {}

    # Output cut before the end (timeout, connection lost): do not compare partial data
    if 'end' not in sections:
        raise ValueError('incomplete gather output (no "### end" marker)')

    # CPU, from lscpu
    cpu = {}
    for line in sections.get('lscpu', []):
        if ':' not in line:
            continue
        key, _, value = line.partition(':')
        key = key.strip()
        value = value.strip()
        if key == 'Architecture':
            cpu['architecture'] = value
        elif key == 'CPU(s)':
            cpu['count'] = int(value)
        elif key == 'Socket(s)':
            cpu['sockets'] = int(value)
        elif key == 'Core(s) per socket':
            cpu['cores_per_socket'] = int(value)
        elif key == 'Thread(s) per core':
            cpu['threads_per_core'] = int(value)
        elif key == 'Model name':
            cpu['model'] = value
    gathered['cpu'] = cpu

    # OS, from /etc/os-release
    os_data = {}
    for line in sections.get('os-release', []):
        if '=' not in line or line.startswith('#'):
            continue
        key, _, value = line.partition('=')
        value = value.strip().strip('"')
        if key == 'ID':
            os_data['id'] = value
            os_data['distribution'] = OS_RELEASE_IDS.get(value, value)
        elif key == 'VERSION_ID':
            os_data['version'] = value
        elif key == 'PRETTY_NAME':
            os_data['pretty_name'] = value
    gathered['os'] = os_data

    kernel_lines = sections.get('kernel', [])
    if len(kernel_lines) > 0:
        gathered['kernel'] = kernel_lines[0].strip()

    firewall_lines = sections.get('firewall', [])
    gathered['firewall'] = len(firewall_lines) > 0 and firewall_lines[0].strip() == 'active'

    # SELinux mode, lower case like os_access_control. No getenforce: SELinux not available.
    selinux_lines = sections.get('selinux', [])
    if len(selinux_lines) > 0 and selinux_lines[0].strip() != '':
        gathered['access_control'] = selinux_lines[0].strip().lower()
    else:
        gathered['access_control'] = 'none'

    gpus = []
    for line in sections.get('gpu', []):
        if line.strip() != '':
            gpus.append(line.strip())
    gathered['gpu'] = gpus

    # Network interfaces: addresses from ip -json, speed and IB rate from sysfs
    speeds = {}
    for line in sections.get('speed', []):
        if '|' not in line:
            continue
        name, _, speed = line.partition('|')
        speed = speed.strip()
        if speed.lstrip('-').isdigit() and int(speed) > 0:
            speeds[name] = int(speed)
        else:
            speeds[name] = None
    ib_rates = {}
    for line in sections.get('ib_rate', []):
        if '|' not in line:
            continue
        name, _, rate = line.partition('|')
        ib_rates[name] = rate.strip() or None
    interfaces = []
    ip_text = '\n'.join(sections.get('ip', []))
    if ip_text.strip() != '':
        for iface in json.loads(ip_text):
            name = iface.get('ifname', '')
            if name == 'lo':
                continue
            ip4 = []
            for addr in iface.get('addr_info', []):
                if addr.get('family') == 'inet':
                    ip4.append('{}/{}'.format(addr['local'], addr['prefixlen']))
            interfaces.append({
                'name': name,
                'ip4': ip4,
                'speed_mbps': speeds.get(name),
                'ib_rate': ib_rates.get(name),
            })
    gathered['network_interfaces'] = interfaces

    # PCIe links, plus a description from lspci -D -mm
    devices = []
    for line in sections.get('pcie', []):
        parts = line.split('|')
        if len(parts) != 5:
            continue
        slot, width, speed, max_width, max_speed = parts
        device = {'name': slot, 'width': None, 'speed': speed, 'max_width': None, 'max_speed': max_speed}
        if width.isdigit():
            device['width'] = int(width)
        if max_width.isdigit():
            device['max_width'] = int(max_width)
        devices.append(device)
    for line in sections.get('lspci', []):
        try:
            fields = shlex.split(line)
        except ValueError:
            continue
        if len(fields) < 4:
            continue
        for device in devices:
            if device['name'] == fields[0]:
                device['description'] = '{} {}'.format(fields[2], fields[3])
    gathered['pcie'] = devices

    return gathered


# ─── comparison ─────────────────────────────────────────────────────────────────

def compare(expected, gathered):
    findings = []

    if 'cpu' in expected:
        for key in expected['cpu']:
            found = gathered['cpu'].get(key)
            if str(found) != str(expected['cpu'][key]):
                findings.append('cpu.{}: expected {}, found {}'.format(key, expected['cpu'][key], found))

    if 'gpu' in expected:
        if sorted(expected['gpu']) != sorted(gathered['gpu']):
            findings.append('gpu: expected {} ({}), found {} ({})'.format(
                len(expected['gpu']), ', '.join(expected['gpu']) or 'none',
                len(gathered['gpu']), ', '.join(gathered['gpu']) or 'none'))

    if 'pcie' in expected:
        for expected_device in expected['pcie']:
            found_device = None
            for device in gathered['pcie']:
                if device['name'] == expected_device['name']:
                    found_device = device
            if found_device is None:
                findings.append('pcie {}: not found'.format(expected_device['name']))
                continue
            if 'width' in expected_device and str(found_device['width']) != str(expected_device['width']):
                findings.append('pcie {}: expected width x{}, found x{}'.format(
                    expected_device['name'], expected_device['width'], found_device['width']))
            if 'speed' in expected_device and found_device['speed'] != str(expected_device['speed']):
                findings.append('pcie {}: expected speed {}, found {}'.format(
                    expected_device['name'], expected_device['speed'], found_device['speed']))

    if 'os' in expected:
        expected_distribution = expected['os']['distribution'].lower()
        found_distribution = gathered['os'].get('distribution', '').lower()
        if expected_distribution != '' and expected_distribution != found_distribution:
            findings.append('os.distribution: expected {}, found {}'.format(expected_distribution, found_distribution))
        # Inventory often holds the major version only: "9" matches "9.4"
        expected_version = expected['os']['version']
        found_version = gathered['os'].get('version', '')
        if expected_version != '' and found_version != expected_version and not found_version.startswith(expected_version + '.'):
            findings.append('os.version: expected {}, found {}'.format(expected_version, found_version))

    if 'kernel' in expected:
        if gathered.get('kernel') != expected['kernel']:
            findings.append('kernel: expected {}, found {}'.format(expected['kernel'], gathered.get('kernel')))

    if 'firewall' in expected:
        if gathered['firewall'] != expected['firewall']:
            findings.append('firewall: expected {}, found {}'.format(
                'active' if expected['firewall'] else 'inactive',
                'active' if gathered['firewall'] else 'inactive'))

    if 'access_control' in expected:
        found = gathered['access_control']
        # No SELinux at all is the same as SELinux disabled
        if found == 'none':
            found = 'disabled'
        if found != expected['access_control']:
            findings.append('access_control: expected {}, found {}'.format(expected['access_control'], found))

    if 'network_interfaces' in expected:
        for expected_iface in expected['network_interfaces']:
            found_iface = None
            for iface in gathered['network_interfaces']:
                if iface['name'] == expected_iface['name']:
                    found_iface = iface
            if found_iface is None:
                findings.append('network interface {}: not found'.format(expected_iface['name']))
                continue
            if 'ip4' in expected_iface:
                found_ips = []
                for address in found_iface['ip4']:
                    found_ips.append(address.split('/')[0])
                if str(expected_iface['ip4']) not in found_ips:
                    findings.append('network interface {}: expected ip4 {}, found {}'.format(
                        expected_iface['name'], expected_iface['ip4'], ', '.join(found_ips) or 'none'))
            if 'ib_rate' in expected_iface:
                if found_iface['ib_rate'] != expected_iface['ib_rate']:
                    findings.append('network interface {}: expected ib_rate {}, found {}'.format(
                        expected_iface['name'], expected_iface['ib_rate'], found_iface['ib_rate']))

    return findings
