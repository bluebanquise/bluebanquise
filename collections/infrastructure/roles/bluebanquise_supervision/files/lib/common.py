"""
Shared code of bluebanquise-supervision: used by the CLI and by every daemon (probe, api,
exporter). Installed in /usr/lib/bluebanquise/bluebanquise-supervision/lib/, and imported with a
plain `import common` after adding this folder to sys.path.

Files, per host, under hosts_data_path/<hostname>/:
  probes.yml        last probe pass results (written by the probe daemon only)
  gathered.yml      raw data gathered for the drift check (written by the probe daemon only)
  maintenance.yml   {active, since, by, reason}
  events.yml        append-only list of events: Error, Action, Acknowledge, MaintenanceStart,
                    MaintenanceEnd, Note
  .lock             lock file, taken for every read-modify-write of events.yml/maintenance.yml

A host is "latched" when an Error event was written and not acknowledged yet: there is no status
file, the latch is read from events.yml, the single source of truth.

Every file is written atomically (temporary file in the same folder, then os.replace()), so a
reader never sees a half-written file and does not need the lock.
"""

import contextlib
import fcntl
import grp
import logging
import os
import pwd
import sys
import threading
import yaml
from datetime import datetime

SETTINGS_FILE = '/etc/bluebanquise/bluebanquise-supervision/bluebanquise-supervision.yml'

LOG_FORMAT = '%(asctime)s [%(levelname)s] %(message)s'

# libyaml based loader/dumper are about 10 times faster than pure Python ones, use them when
# PyYAML was built with libyaml.
if yaml.__with_libyaml__:
    YAML_LOADER = yaml.CSafeLoader
    YAML_DUMPER = yaml.CSafeDumper
else:
    YAML_LOADER = yaml.SafeLoader
    YAML_DUMPER = yaml.SafeDumper


# ─── settings, logging, privileges ─────────────────────────────────────────────

def setup_logging(log_level):
    level = getattr(logging, str(log_level).upper(), logging.INFO)
    root = logging.getLogger()
    root.setLevel(level)
    if not root.handlers:
        handler = logging.StreamHandler(sys.stdout)
        handler.setFormatter(logging.Formatter(LOG_FORMAT))
        root.addHandler(handler)


def load_settings(path=SETTINGS_FILE):
    logging.debug('Loading settings from %s', path)
    with open(path, 'r') as f:
        settings = yaml.load(f, Loader=YAML_LOADER)
    return settings


def load_hosts(settings):
    """Supervised hosts, as generated by the role from the inventory."""
    logging.debug('Loading hosts from %s', settings['hosts_file'])
    with open(settings['hosts_file'], 'r') as f:
        data = yaml.load(f, Loader=YAML_LOADER) or {}
    hosts = data.get('hosts') or {}
    logging.debug('Loaded %d host(s)', len(hosts))
    return hosts


def drop_privileges(user):
    """If started as root, switch to the unprivileged user before touching any file, so every
    file keeps the right owner. Same as pxe_stack daemon and bluebanquise-bootset."""
    os.umask(0o027)
    if os.getuid() != 0:
        return
    pw = pwd.getpwnam(user)
    os.setgroups([])
    os.setgid(pw.pw_gid)
    os.setuid(pw.pw_uid)
    # ssh reads HOME to find known_hosts, keep it consistent with the new user
    os.environ['HOME'] = pw.pw_dir
    logging.debug('Dropped privileges to %s (uid=%d gid=%d, group %s)',
                  user, pw.pw_uid, pw.pw_gid, grp.getgrgid(pw.pw_gid).gr_name)


def now():
    """Local time with UTC offset, to the second: 2026-11-05T10:15:00+01:00"""
    return datetime.now().astimezone().isoformat(timespec='seconds')


# ─── files ──────────────────────────────────────────────────────────────────────

def host_file(settings, hostname, filename):
    return os.path.join(settings['hosts_data_path'], hostname, filename)


def read_yaml(path, default):
    try:
        with open(path, 'r') as f:
            data = yaml.load(f, Loader=YAML_LOADER)
    except FileNotFoundError:
        return default
    if data is None:
        return default
    return data


def write_yaml(path, data):
    """Atomic write: temporary file in the same folder, then os.replace(). The temporary file
    name holds the process and thread ids, so two writers never share it."""
    folder = os.path.dirname(path)
    os.makedirs(folder, exist_ok=True)
    tmp_path = os.path.join(folder, '.{}.{}.{}.tmp'.format(
        os.path.basename(path), os.getpid(), threading.get_ident()))
    with open(tmp_path, 'w') as f:
        yaml.dump(data, f, Dumper=YAML_DUMPER, default_flow_style=False, allow_unicode=True,
                  sort_keys=False)
    os.replace(tmp_path, path)


@contextlib.contextmanager
def host_lock(settings, hostname):
    """Exclusive lock on the host folder, for read-modify-write of events.yml/maintenance.yml.
    flock is per open file, so it also works between threads of the same process."""
    lock_path = host_file(settings, hostname, '.lock')
    os.makedirs(os.path.dirname(lock_path), exist_ok=True)
    lock_file = open(lock_path, 'w')
    try:
        fcntl.flock(lock_file.fileno(), fcntl.LOCK_EX)
        yield
    finally:
        fcntl.flock(lock_file.fileno(), fcntl.LOCK_UN)
        lock_file.close()


# ─── events ─────────────────────────────────────────────────────────────────────

def read_events(settings, hostname):
    return read_yaml(host_file(settings, hostname, 'events.yml'), [])


def _append_event_unlocked(settings, hostname, kind, message, by=None):
    """Caller must hold host_lock."""
    events = read_events(settings, hostname)
    event = {
        'number': len(events) + 1,
        'kind': kind,
        'time': now(),
    }
    if by is not None:
        event['by'] = by
    event['message'] = message
    events.append(event)
    write_yaml(host_file(settings, hostname, 'events.yml'), events)
    logging.info('[%s] Event #%d %s: %s', hostname, event['number'], kind, message)
    return event


def append_event(settings, hostname, kind, message, by=None):
    with host_lock(settings, hostname):
        return _append_event_unlocked(settings, hostname, kind, message, by)


def is_latched(events):
    """True if an Error event was written after the last Acknowledge event."""
    latched = False
    for event in events:
        if event['kind'] == 'Error':
            latched = True
        elif event['kind'] == 'Acknowledge':
            latched = False
    return latched


def latch_error(settings, hostname, message):
    """Write an Error event, only if the host is not already latched. Returns True if the event
    was written (this is a new error), False if the host was already latched."""
    with host_lock(settings, hostname):
        events = read_events(settings, hostname)
        if is_latched(events):
            logging.debug('[%s] Already latched, no new Error event', hostname)
            return False
        _append_event_unlocked(settings, hostname, 'Error', message)
        return True


def acknowledge(settings, hostname, by, reason):
    """Returns (True, message) if acknowledged, (False, message) if refused."""
    with host_lock(settings, hostname):
        events = read_events(settings, hostname)
        if not is_latched(events):
            return False, '{} is not in error, nothing to acknowledge'.format(hostname)
        _append_event_unlocked(settings, hostname, 'Acknowledge', reason, by)
    return True, '{} acknowledged'.format(hostname)


def add_note(settings, hostname, by, text):
    append_event(settings, hostname, 'Note', text, by)
    return True, 'Note added to {}'.format(hostname)


# ─── maintenance ────────────────────────────────────────────────────────────────

def read_maintenance(settings, hostname):
    default = {'active': False, 'since': None, 'by': None, 'reason': None}
    return read_yaml(host_file(settings, hostname, 'maintenance.yml'), default)


def start_maintenance(settings, hostname, by, reason):
    with host_lock(settings, hostname):
        maintenance = read_maintenance(settings, hostname)
        if maintenance['active']:
            return False, '{} is already in maintenance (since {}, by {})'.format(
                hostname, maintenance['since'], maintenance['by'])
        maintenance = {'active': True, 'since': now(), 'by': by, 'reason': reason}
        write_yaml(host_file(settings, hostname, 'maintenance.yml'), maintenance)
        _append_event_unlocked(settings, hostname, 'MaintenanceStart', reason, by)
    return True, '{} is now in maintenance'.format(hostname)


def stop_maintenance(settings, hostname, by, reason):
    with host_lock(settings, hostname):
        maintenance = read_maintenance(settings, hostname)
        if not maintenance['active']:
            return False, '{} is not in maintenance'.format(hostname)
        maintenance = {'active': False, 'since': None, 'by': None, 'reason': None}
        write_yaml(host_file(settings, hostname, 'maintenance.yml'), maintenance)
        _append_event_unlocked(settings, hostname, 'MaintenanceEnd', reason, by)
    return True, '{} is no longer in maintenance'.format(hostname)


# ─── probe results and on-demand requests ─────────────────────────────────────

def read_probes(settings, hostname):
    return read_yaml(host_file(settings, hostname, 'probes.yml'), None)


def request_probe(settings, hostname):
    """Ask the probe daemon to probe this host now: an empty file named after the host."""
    os.makedirs(settings['requests_path'], exist_ok=True)
    with open(os.path.join(settings['requests_path'], hostname), 'w'):
        pass
    return True, 'Probe of {} requested'.format(hostname)


# ─── host summary (CLI status, API, exporter) ─────────────────────────────────

def host_summary(settings, hostname, host_conf):
    """One place deciding the state of a host:
         maintenance  host is in maintenance (wins over everything else)
         error        last probe pass failed, or host latched (error not acknowledged yet)
         ok           last probe pass succeeded, nothing to acknowledge
         unknown      never probed"""
    probes = read_probes(settings, hostname)
    maintenance = read_maintenance(settings, hostname)
    latched = is_latched(read_events(settings, hostname))

    if probes is None:
        last_probe = None
        failed = []
    else:
        last_probe = probes['finished']
        failed = probes['failed']

    if maintenance['active']:
        state = 'maintenance'
    elif latched or len(failed) > 0:
        state = 'error'
    elif probes is None:
        state = 'unknown'
    else:
        state = 'ok'

    return {
        'host': hostname,
        'group': host_conf.get('group', 'none'),
        'state': state,
        'latched': latched,
        'maintenance': maintenance['active'],
        'last_probe': last_probe,
        'failed': failed,
    }
